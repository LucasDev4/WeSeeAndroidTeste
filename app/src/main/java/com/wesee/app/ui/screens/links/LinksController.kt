package com.wesee.app.ui.screens.links

import android.os.SystemClock
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableLongStateOf
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import com.wesee.app.data.UserStore
import com.wesee.app.network.ApiResult
import com.wesee.app.network.AtlasApi
import com.wesee.app.network.CodigoGerado
import com.wesee.app.network.VinculoItem
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch

/** Dígitos do código de vinculação. Deve ser igual a `vinculo.codigo-tamanho` do backend. */
const val VINCULO_CODE_LENGTH = 6

enum class LinksStep { Closed, List, Code }

/**
 * Lógica do modal de vínculos (sem chamadas HTTP dentro de Composables).
 * [isGuardian] = true → conta RESPONSAVEL (digita o código); false → PCD_VISUAL (gera o código).
 * Nada é dado como "concluído" antes da resposta do servidor.
 */
class LinksController(
    private val scope: CoroutineScope,
    private val userStore: UserStore,
    val isGuardian: Boolean,
) {
    var step by mutableStateOf(LinksStep.Closed); private set

    // lista
    var items by mutableStateOf<List<VinculoItem>>(emptyList()); private set
    var loadingList by mutableStateOf(false); private set
    var listError by mutableStateOf<String?>(null); private set
    /** Mensagem de resultado (sucesso/pendência) mostrada na lista. */
    var notice by mutableStateOf<String?>(null); private set

    // etapa do código
    var input by mutableStateOf(""); private set
    var busy by mutableStateOf(false); private set
    var codeError by mutableStateOf<String?>(null); private set
    var generated by mutableStateOf<CodigoGerado?>(null); private set
    /** Momento (elapsedRealtime) em que o código gerado expira, calculado com a validade informada pelo servidor. */
    var expiresAtMs by mutableLongStateOf(0L); private set

    val title: String get() = if (isGuardian) "Pessoas vinculadas:" else "Meus Responsáveis:"

    fun open() { step = LinksStep.List; notice = null; refresh() }
    fun close() { step = LinksStep.Closed; resetCode() }

    /** Voltar: etapa de código → lista; lista → fecha o modal. */
    fun back() {
        when (step) {
            LinksStep.Code -> { resetCode(); step = LinksStep.List }
            LinksStep.List -> close()
            LinksStep.Closed -> Unit
        }
    }

    private fun resetCode() { input = ""; codeError = null; generated = null; busy = false; expiresAtMs = 0L }

    private fun token(): String? = userStore.token

    fun refresh() {
        if (loadingList) return
        val t = token() ?: run { listError = "Sessão expirada. Entre novamente."; return }
        scope.launch {
            loadingList = true; listError = null
            when (val r = AtlasApi.listarVinculos(t)) {
                is ApiResult.Success -> items = r.value
                is ApiResult.Error -> listError = friendly(r)
            }
            loadingList = false
        }
    }

    /** Botão "Adicionar vínculo". Responsável: abre os campos; PCD: pede o código ao backend. */
    fun startAdd() {
        notice = null; resetCode(); step = LinksStep.Code
        if (!isGuardian) generate()
    }

    // ---------- Responsável: digitar e confirmar ----------

    fun onInput(raw: String) {
        if (busy) return
        input = raw.filter { it.isDigit() }.take(VINCULO_CODE_LENGTH)
        codeError = null
    }

    fun confirm() {
        if (busy) return
        if (input.length != VINCULO_CODE_LENGTH) { codeError = "Digite os $VINCULO_CODE_LENGTH números do código."; return }
        val t = token() ?: run { codeError = "Sessão expirada. Entre novamente."; return }
        scope.launch {
            busy = true; codeError = null
            when (val r = AtlasApi.solicitarVinculo(t, input)) {
                is ApiResult.Success -> {
                    // lista atualizada com o estado REAL retornado pelo servidor
                    when (val l = AtlasApi.listarVinculos(t)) {
                        is ApiResult.Success -> items = l.value
                        is ApiResult.Error -> Unit
                    }
                    notice = if (r.value.status == "ATIVO") "Vínculo ativado com ${r.value.nome}."
                    else "Solicitação enviada. Aguardando confirmação de ${r.value.nome}."
                    resetCode(); step = LinksStep.List
                }
                is ApiResult.Error -> { codeError = friendly(r); busy = false }
            }
        }
    }

    // ---------- PCD: gerar e exibir ----------

    fun generate() {
        if (busy) return
        val t = token() ?: run { codeError = "Sessão expirada. Entre novamente."; return }
        scope.launch {
            busy = true; codeError = null; generated = null
            when (val r = AtlasApi.gerarCodigo(t)) {
                is ApiResult.Success -> {
                    generated = r.value
                    expiresAtMs = SystemClock.elapsedRealtime() + r.value.validadeSegundos * 1000
                }
                is ApiResult.Error -> codeError = friendly(r)
            }
            busy = false
        }
    }

    /**
     * PCD: enquanto o código está na tela, consulta o servidor para refletir o estado real
     * (se alguém usou o código, o novo responsável aparece e voltamos à lista).
     */
    suspend fun watchForUse() {
        val t = token() ?: return
        val known = items.map { it.id }.toSet()
        while (step == LinksStep.Code && generated != null && SystemClock.elapsedRealtime() < expiresAtMs) {
            delay(4000)
            val r = AtlasApi.listarVinculos(t)
            if (r is ApiResult.Success) {
                val novo = r.value.firstOrNull { it.id !in known }
                if (novo != null) {
                    items = r.value
                    notice = "${novo.nome} agora é seu responsável."
                    resetCode(); step = LinksStep.List
                    return
                }
            }
        }
    }

    private fun friendly(e: ApiResult.Error): String = when (e.code) {
        -1 -> "Sem conexão com o servidor. Verifique a internet e tente de novo."
        401 -> "Sessão expirada. Entre novamente."
        400, 403, 409, 429 -> e.fields.values.firstOrNull() ?: e.message // mensagens do backend já são claras
        else -> "Não foi possível concluir agora. Tente novamente."
    }
}
